/**
 * The resource-monitor guard for `mach`.
 *
 * mozbuild's resource monitor calls `psutil.virtual_memory()` at startup and
 * again from `mozbuild.base._run_make`. On some hosts those raise
 * `RuntimeError: host_statistics64(HOST_VM_INFO64) syscall failed`, and a
 * `SystemResourceMonitor.__init__` that fails partway leaves an instance
 * without `poll_interval`, so later polling dies with an `AttributeError`.
 * Either aborts `mach build` before the compiler runs.
 *
 * The guard is a `fireforge_mach_guard.pth` and module pair in the
 * site-packages of every mach virtualenv. A `sitecustomize.py` on PYTHONPATH
 * is not enough: mach re-executes itself inside its private virtualenv and
 * drops PYTHONPATH. A `.pth` file runs at interpreter startup from the
 * virtualenv's own site-packages, which survives that. The PYTHONPATH copy
 * covers only the first run, before any virtualenv exists.
 *
 * What the Python guards, and why each shape matters:
 *
 *  - `psutil.virtual_memory`, `swap_memory`, `cpu_percent`, `cpu_times` and
 *    `disk_io_counters` are wrapped module-wide, so every call site degrades
 *    to a warning and a zeroed reading. The fallback has the arity of that
 *    function's own result: mozsystemmonitor captures each reading's type at
 *    construction and rebuilds collector samples with `type(reading)(*values)`,
 *    so a memory-shaped reading in the swap position makes the parent reject
 *    every sample, the pipe fills, the collector child blocks in `send()`,
 *    and mach hangs in its exit-time `waitpid`. psutil's own result
 *    namedtuple is used where it resolves, otherwise a module-level one of
 *    the guard's (module-level so readings pickle across the collector pipe).
 *  - `SystemResourceMonitor` construction is guarded through an import hook:
 *    `poll_interval` is set before the real `__init__`, a failing `__init__`
 *    marks the instance degraded, and every monitor method is inert on a
 *    degraded instance. Aggregate methods return zeroed shapes rather than
 *    `None` where callers subscript the result.
 *  - Once any degradation was seen in the process, monitors stay inert and a
 *    live collector child is terminated and its pipe drained, so a malformed
 *    sample stream cannot wedge mach's shutdown.
 *  - `BuildMonitor.log_resource_usage` warns and continues on any exception,
 *    so end-of-build reporting cannot fail a build whose artifacts are complete.
 */
