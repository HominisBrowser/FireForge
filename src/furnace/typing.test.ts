import { readFile } from 'node:fs/promises';
import { join } from 'node:path';

import { describe, expect, it } from 'vitest';

import { makeFurnaceFixture } from '../testing/furnace.js';
import { useTempDir } from '../testing/temp.js';
import { loadFurnaceConfig, typingDrift, updateTypingFiles } from './index.js';

const dir = useTempDir();

const entry = (extra: object = {}): object => ({
  description: '',
  targetPath: 'x',
  register: true,
  localized: false,
  ...extra,
});

const JSCONFIG = `{
  "compilerOptions": {
    "paths": {
      "resource:///modules/acme/*": ["../../modules/acme/*"],
      "chrome://global/content/elements/moz-acme-gone.mjs": ["../../../../components/custom/moz-acme-gone/moz-acme-gone.mjs"],
      "chrome://global/content/elements/moz-acme-a.mjs": ["../../../../components/custom/moz-acme-a/moz-acme-a.mjs"]
    }
  }
}
`;

describe('typing files', () => {
  it('maintains the component paths of a jsconfig, relative to its tracked copy, keeping foreign entries', async () => {
    const f = await makeFurnaceFixture(dir(), {
      furnace: {
        version: 1,
        componentPrefix: 'moz-',
        typecheckJsconfig: 'engine/browser/base/content/jsconfig.json',
        custom: { 'moz-acme-a': entry(), 'moz-acme-b': entry() },
      },
      files: {
        'components/custom/moz-acme-a/moz-acme-a.mjs': '',
        'components/custom/moz-acme-b/moz-acme-b.mjs': '',
        'components/custom/moz-acme-b/moz-acme-b-rows.mjs': '',
      },
      engine: { 'browser/base/content/jsconfig.json': JSCONFIG },
    });
    const config = await loadFurnaceConfig(f.project);
    expect(await typingDrift(f.project, config, f.tracked)).toEqual([
      {
        file: 'engine/browser/base/content/jsconfig.json',
        detail:
          'orphaned chrome://global/content/elements/moz-acme-gone.mjs; ' +
          'missing chrome://global/content/elements/moz-acme-b-rows.mjs; ' +
          'missing chrome://global/content/elements/moz-acme-b.mjs',
      },
    ]);
    await updateTypingFiles(f.project, f.tracked);
    const written = JSON.parse(
      await readFile(join(f.engineDir, 'browser/base/content/jsconfig.json'), 'utf8')
    ) as {
      compilerOptions: { paths: Record<string, string[]> };
    };
    expect(written.compilerOptions.paths).toEqual({
      'resource:///modules/acme/*': ['../../modules/acme/*'],
      'chrome://global/content/elements/moz-acme-a.mjs': [
        '../../../../components/custom/moz-acme-a/moz-acme-a.mjs',
      ],
      'chrome://global/content/elements/moz-acme-b-rows.mjs': [
        '../../../../components/custom/moz-acme-b/moz-acme-b-rows.mjs',
      ],
      'chrome://global/content/elements/moz-acme-b.mjs': [
        '../../../../components/custom/moz-acme-b/moz-acme-b.mjs',
      ],
    });
    expect(await typingDrift(f.project, config, f.tracked)).toEqual([]);
  });

  it('maps each registered element whose module exports its class', async () => {
    const f = await makeFurnaceFixture(dir(), {
      furnace: {
        version: 1,
        componentPrefix: 'moz-',
        typecheckTagMap: 'types/widgets.d.ts',
        custom: {
          'moz-acme-a': entry(),
          'moz-acme-b': entry(),
          'moz-acme-lib': entry({ kind: 'library', register: false }),
        },
      },
      files: {
        'components/custom/moz-acme-a/moz-acme-a.mjs':
          'class A extends HTMLElement {}\nexport { A as Alpha };\ncustomElements.define("moz-acme-a", A);\n' +
          'class Hidden extends HTMLElement {}\ncustomElements.define("moz-acme-hidden", Hidden);\n',
        'components/custom/moz-acme-b/moz-acme-b.mjs':
          'export default class B extends HTMLElement {}\ncustomElements.define("moz-acme-b", B);\n' +
          'export class Link extends HTMLAnchorElement {}\ncustomElements.define("moz-acme-link", Link, { extends: "a" });\n',
        'components/custom/moz-acme-lib/moz-acme-lib.mjs':
          'export class L extends HTMLElement {}\ncustomElements.define("moz-acme-lib", L);\n',
      },
    });
    await updateTypingFiles(f.project, f.tracked);
    expect(await readFile(join(f.root, 'types/widgets.d.ts'), 'utf8')).toBe(
      [
        '// Generated by FireForge from furnace.json (typecheckTagMap). Do not edit:',
        '// fireforge furnace types rewrites it, and furnace validate reports drift.',
        'interface HTMLElementTagNameMap {',
        '  "moz-acme-a": HTMLElement & import("chrome://global/content/elements/moz-acme-a.mjs").Alpha;',
        '  "moz-acme-b": HTMLElement & import("chrome://global/content/elements/moz-acme-b.mjs").default;',
        '}',
        '',
      ].join('\n')
    );
  });

  it('refuses a jsconfig that does not exist', async () => {
    const f = await makeFurnaceFixture(dir(), {
      furnace: { version: 1, componentPrefix: 'moz-', typecheckJsconfig: 'missing.json' },
    });
    await expect(updateTypingFiles(f.project, f.tracked)).rejects.toMatchObject({
      code: 'furnace-jsconfig-invalid',
    });
  });
});
