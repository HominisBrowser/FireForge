import { readFile, stat, utimes } from 'node:fs/promises';
import { join } from 'node:path';

import { describe, expect, it } from 'vitest';

import { ExitCode } from '../kernel/errors.js';
import { makeEngineProject, makeProjectEngine } from '../testing/engine.js';
import { useTempDir, writeTree } from '../testing/temp.js';
import { brandingDirectory, renderMozconfig, withoutObjdir, writeMozconfig } from './mozconfig.js';

const dir = useTempDir();
const PLATFORM = `configs/${process.platform}.mozconfig`;

describe('renderMozconfig', () => {
  it('joins the common and platform templates, substitutes the identity and places the object directory', async () => {
    const project = await makeEngineProject(dir(), {
      files: {
        'configs/common.mozconfig':
          'ac_add_options --with-app-name=${binaryName}\nexport MOZ_APP_VENDOR="${vendor}"\n',
        [PLATFORM]: '# ${name} (${appId})\nac_add_options --enable-debug\n',
      },
    });
    expect(await renderMozconfig({ project })).toBe(
      [
        '# Generated by FireForge from configs/. Edit the templates, not this file.',
        'ac_add_options --with-distribution-id=org.example',
        '',
        '# configs/common.mozconfig',
        'ac_add_options --with-app-name=testbrowser',
        'export MOZ_APP_VENDOR="Example"',
        '',
        `# ${PLATFORM}`,
        '# Test Browser (org.example.mine)',
        'ac_add_options --enable-debug',
        '',
        'mk_add_options MOZ_OBJDIR=@TOPSRCDIR@/obj-fireforge',
        '',
      ].join('\n')
    );
  });

  it('does not expand replacement patterns in an identity value', async () => {
    const project = await makeEngineProject(dir(), {
      config: { name: 'Cash $& Carry' },
      files: { [PLATFORM]: 'export NAME="${name}"\n' },
    });
    expect(await renderMozconfig({ project })).toContain('export NAME="Cash $& Carry"');
  });

  it('works without a common template and refuses without the platform one', async () => {
    const project = await makeEngineProject(dir());
    await writeTree(project.root, { 'configs/common.mozconfig': '' });
    expect(await renderMozconfig({ project })).toContain(`# ${PLATFORM}`);
    const bare = await makeEngineProject(dir(), {}, 'bare');
    await writeTree(bare.root, { [PLATFORM]: 'mk_add_options MOZ_OBJDIR=/elsewhere\n' });
    await expect(renderMozconfig({ project: bare })).rejects.toMatchObject({
      code: 'mozconfig-invalid',
      exitCode: ExitCode.CONFIG_ERROR,
      message: expect.stringContaining('sets MOZ_OBJDIR') as string,
    });
    const { rm } = await import('node:fs/promises');
    await rm(join(bare.root, PLATFORM));
    await expect(renderMozconfig({ project: bare })).rejects.toMatchObject({
      code: 'mozconfig-invalid',
      message: expect.stringContaining('does not exist') as string,
    });
  });
});

describe('writeMozconfig', () => {
  it('writes the file once and leaves an unchanged one untouched, modification time included', async () => {
    const project = await makeEngineProject(dir());
    const workspace = await makeProjectEngine(project);
    const path = join(workspace.engineDir, 'mozconfig');
    expect(await writeMozconfig(workspace)).toBe(true);
    const long = new Date('2001-01-01T00:00:00Z');
    await utimes(path, long, long);
    expect(await writeMozconfig(workspace)).toBe(false);
    expect((await stat(path)).mtimeMs).toBe(long.getTime());

    await writeTree(project.root, { [PLATFORM]: 'ac_add_options --enable-debug\n' });
    expect(await writeMozconfig(workspace)).toBe(true);
    expect(await readFile(path, 'utf8')).toContain('--enable-debug');
  });

  it('refuses a branding directory the engine does not have, before mach would', async () => {
    const project = await makeEngineProject(dir(), {
      files: { [PLATFORM]: 'ac_add_options --with-branding=browser/branding/testbrowser\n' },
    });
    const workspace = await makeProjectEngine(project);
    await expect(writeMozconfig(workspace)).rejects.toMatchObject({
      code: 'mozconfig-invalid',
      message: expect.stringContaining('browser/branding/testbrowser/moz.build') as string,
    });
    await writeTree(workspace.engineDir, { 'browser/branding/testbrowser/moz.build': '' });
    expect(await writeMozconfig(workspace)).toBe(true);
  });
});

describe('withoutObjdir', () => {
  it('drops every MOZ_OBJDIR declaration and nothing else', () => {
    expect(
      withoutObjdir(
        'ac_add_options --enable-debug\nmk_add_options MOZ_OBJDIR=@TOPSRCDIR@/obj-x\n# MOZ_OBJDIR is set above\nexport MOZ_OBJDIR=/tmp/o\n'
      )
    ).toBe('ac_add_options --enable-debug\n# MOZ_OBJDIR is set above\n');
    expect(withoutObjdir('ac_add_options --enable-debug\n')).toBeUndefined();
  });
});

describe('brandingDirectory', () => {
  it.each([
    ['ac_add_options --with-branding=browser/branding/a\n', 'browser/branding/a'],
    ['--with-branding=a\nac_add_options --with-branding = b\n', 'b'],
    ['ac_add_options --with-branding=browser\\branding\\win\n', 'browser/branding/win'],
    ['# ac_add_options --with-branding=commented\n', undefined],
    ['ac_add_options --enable-debug\n', undefined],
  ])('%j selects %j', (mozconfig, expected) => {
    expect(brandingDirectory(mozconfig)).toBe(expected);
  });
});
