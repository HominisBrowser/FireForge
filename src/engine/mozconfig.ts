/**
 * The engine's `mozconfig`, generated from the project's `configs/`
 * templates: `common.mozconfig` (optional), then the platform's
 * (`darwin.mozconfig`, `linux.mozconfig`, `win32.mozconfig`), with the
 * project's identity substituted for `${name}`, `${vendor}`, `${appId}` and
 * `${binaryName}`. FireForge places the object directory itself, so every
 * workspace has it at the same relative path.
 */
import { join } from 'node:path';

import { ExitCode, FireForgeError } from '../kernel/errors.js';
import { exists, readTextIfExists, writeFileIfChanged } from '../kernel/fs.js';
import { verbose } from '../kernel/log.js';
import { OBJDIR_NAME, type Workspace } from './workspace.js';

/** A `MOZ_OBJDIR` declaration in either spelling mach honours. */
const MOZ_OBJDIR = /^\s*(?:mk_add_options\s+|export\s+)?MOZ_OBJDIR\s*=/m;

/**
 * A mozconfig template without its `MOZ_OBJDIR` declarations, which the
 * generated mozconfig refuses because FireForge places the object directory
 * itself. Undefined when the template declares none.
 *
 * @param text - The template's content
 */
export function withoutObjdir(text: string): string | undefined {
  const lines = text.split('\n');
  const kept = lines.filter((line) => !MOZ_OBJDIR.test(line));
  return kept.length === lines.length ? undefined : kept.join('\n');
}

/** The last `--with-branding=<path>` wins, as in any shell-evaluated mozconfig. */
const WITH_BRANDING = /^\s*(?:ac_add_options\s+)?--with-branding\s*=\s*(\S+)/gm;

function configError(message: string, hint: string): FireForgeError {
  return new FireForgeError('mozconfig-invalid', message, {
    exitCode: ExitCode.CONFIG_ERROR,
    hint,
  });
}

/**
 * The branding directory a mozconfig selects, or undefined when it names none.
 *
 * @param mozconfig - The mozconfig text
 */
export function brandingDirectory(mozconfig: string): string | undefined {
  return [...mozconfig.matchAll(WITH_BRANDING)].at(-1)?.[1]?.replaceAll('\\', '/');
}

/**
 * Renders the mozconfig a workspace builds with, without writing it.
 *
 * @param workspace - The workspace; its project's `configs/` and identity are read
 * @throws `mozconfig-invalid` (exit code 2) when the platform template is
 *   missing or a template places the object directory
 */
export async function renderMozconfig(workspace: Pick<Workspace, 'project'>): Promise<string> {
  const { config, paths } = workspace.project;
  const values: Readonly<Record<string, string>> = {
    name: config.name,
    vendor: config.vendor,
    appId: config.appId,
    binaryName: config.binaryName,
  };
  const template = async (file: string): Promise<string | undefined> => {
    const text = await readTextIfExists(join(paths.configs, file));
    if (text === undefined) return undefined;
    if (MOZ_OBJDIR.test(text)) {
      throw configError(
        `configs/${file} sets MOZ_OBJDIR`,
        `Remove it: FireForge keeps the object directory at ${OBJDIR_NAME} inside every engine.`
      );
    }
    return text.replace(
      /\$\{(name|vendor|appId|binaryName)\}/g,
      (_, key: string) => values[key] ?? ''
    );
  };
  const platformFile = `${process.platform}.mozconfig`;
  const [common, platform] = [await template('common.mozconfig'), await template(platformFile)];
  if (platform === undefined) {
    throw configError(
      `configs/${platformFile} does not exist`,
      'Create it with the mozconfig options this platform builds with (it may be empty).'
    );
  }
  // Upstream composes the macOS bundle identifier as
  // <distribution id>.<MOZ_MACBUNDLE_ID>, and branding carries only the last
  // segment of the application id, so the rest travels here.
  const distributionId = config.appId.slice(0, config.appId.lastIndexOf('.'));
  return [
    `# Generated by FireForge from configs/. Edit the templates, not this file.`,
    `ac_add_options --with-distribution-id=${distributionId}`,
    '',
    ...(common === undefined ? [] : ['# configs/common.mozconfig', common.trimEnd(), '']),
    `# configs/${platformFile}`,
    platform.trimEnd(),
    '',
    `mk_add_options MOZ_OBJDIR=@TOPSRCDIR@/${OBJDIR_NAME}`,
    '',
  ].join('\n');
}

/**
 * Writes the engine's `mozconfig` when its content would change. An unchanged
 * file keeps its modification time, which is what mach compares its
 * configure output against: rewriting it would re-run configure on every build.
 *
 * @param workspace - The workspace
 * @returns Whether the file was written
 * @throws `mozconfig-invalid` (exit code 2), also when the selected branding
 *   directory is not in the engine
 */
export async function writeMozconfig(
  workspace: Pick<Workspace, 'project' | 'engineDir'>
): Promise<boolean> {
  const content = await renderMozconfig(workspace);
  const branding = brandingDirectory(content);
  if (branding !== undefined && !(await exists(join(workspace.engineDir, branding, 'moz.build')))) {
    throw configError(
      `configs/ selects --with-branding=${branding}, and the engine has no ${branding}/moz.build`,
      'Add the branding directory to the project, or correct the option: configure would fail on it much later.'
    );
  }
  const written = await writeFileIfChanged(join(workspace.engineDir, 'mozconfig'), content);
  if (!written) verbose('mozconfig is unchanged.');
  return written;
}
